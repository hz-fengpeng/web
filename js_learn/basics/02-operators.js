// ============================================
// 运算符 - 与 C/C++ 类似但有区别
// ============================================

// 算术运算符（与 C/C++ 相同）
let a = 10, b = 3;
console.log("加法:", a + b);      // 13
console.log("减法:", a - b);      // 7
console.log("乘法:", a * b);      // 30
console.log("除法:", a / b);      // 3.333... (JS 中除法总是浮点数)
console.log("取模:", a % b);      // 1
console.log("幂运算:", a ** b);   // 1000 (JS 特有)

// ============================================
// 比较运算符 - 注意 == 和 === 的区别
// ============================================

// == 会进行类型转换（不推荐）
console.log("\n== 比较（类型转换）:");
console.log("5 == '5':", 5 == '5');     // true (字符串转为数字)
console.log("0 == false:", 0 == false); // true

// === 严格相等（推荐使用）
console.log("\n=== 比较（严格）:");
console.log("5 === '5':", 5 === '5');     // false
console.log("5 === 5:", 5 === 5);         // true

// ============================================
// 逻辑运算符
// ============================================

let x = true, y = false;
console.log("\n逻辑运算:");
console.log("x && y:", x && y);  // false
console.log("x || y:", x || y);  // true
console.log("!x:", !x);          // false

// ============================================
// 字符串连接（与 C++ 不同）
// ============================================

let firstName = "Zhang";
let lastName = "San";
console.log("\n字符串操作:");
console.log(firstName + " " + lastName);  // 使用 +
console.log(`${firstName} ${lastName}`);  // 模板字符串（推荐）
