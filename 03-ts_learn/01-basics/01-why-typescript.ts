// ============================================
// 01 为什么需要 TypeScript
// ============================================
//
// TypeScript = JavaScript + 类型系统。
// 它不改变 JS 的运行时行为，只在"运行之前"多加一道检查。
//
// 和 C/C++ 最大的不同：TS 的类型只存在于编译期，运行时全部消失。
// 最终产物就是普通 JS，不带任何类型信息，也没有运行时开销。
//
// ============================================
// 先记住两个命令的分工
// ============================================
//
//   在本目录（ts_learn/）下执行：
//
//     node 01-basics/01-why-typescript.ts    ← 运行。node 会把类型擦掉，但**不检查**
//     npm run check                          ← 类型检查。tsc 只检查，**不运行**
//
//   这两个命令是分开的，这是理解 TS 的第一道关：
//   类型写错了，node 照样能跑出结果 —— 因为它根本没看类型。
//
//   （旧版本 node 不能直接跑 .ts，需要先 tsc 编译成 .js 再 node 跑。
//     本机 node 版本够新，内置了类型擦除，所以省掉了这一步。）

// ============================================
// 一、JS 里三个"能跑但错了"的场景
// ============================================
// 下面三段都被注释掉了，因为它们在 TS 里**根本通不过检查**。
// 想看它们真的会报什么错，取消注释后执行 `npm run check`。

// 【场景 1】属性名拼错
//
//   const user = { name: "张三", age: 20 };
//   console.log(user.nmae);   // undefined —— 没有报错，上线了才发现
//
// TS 会直接拦下来，还会猜你想写什么：
//   error TS2339: Property 'nmae' does not exist on type '{ name: string; age: number; }'.
//     Did you mean 'name'?

// 【场景 2】忘了传参数
//
//   function greet(name) { return "你好，" + name; }
//   greet();               // "你好，undefined" —— 也是不报错的
//
// TS：error TS2554: Expected 1 arguments, but got 0.

// 【场景 3】类型用错
//
//   function double(n) { return n * 2; }
//   double("3");    // 6，居然对了 —— JS 偷偷把字符串转成了数字
//   double("三");   // NaN，到这里才暴露，而且离出错的地方已经很远
//
// TS：error TS2345: Argument of type 'string' is not assignable to parameter of type 'number'.

// ============================================
// 二、加上类型之后
// ============================================
// 类型标注的语法是 `名字: 类型` —— 注意类型写在**后面**，
// 和 C/C++ 的 `int count` 正好相反（原因会在 02 里展开）。

const user: { name: string; age: number } = { name: "张三", age: 20 };
console.log("用户：", user.name, user.age);
// console.log(user.nmae);   // ❌ 拼错属性名，tsc 立刻报错，编辑器里还会划红线

function greet(name: string): string {
  return `你好，${name}`;
}
console.log(greet("张三"));
// greet();                   // ❌ error TS2554: 参数少了一个
// greet(123);                // ❌ error TS2345: 参数类型不对

function double(n: number): number {
  return n * 2;
}
console.log("double(21) =", double(21));
// double("三");              // ❌ 传字符串进去，tsc 直接拒绝

// 关键点：这三个错误，**不用运行程序就已经被发现了**。
// 在编辑器里，你还没保存文件，属性名拼错的地方就已经划上了红线。

// ============================================
// 三、类型到底在什么时候存在
// ============================================
// TS 的类型只在两个地方存在：
//   1. 你写的 .ts 源码里
//   2. tsc 检查的时候
// 运行的时候完全没有 —— node 拿到 .ts 后做的第一件事就是把类型全删掉。

const price: number = 19.9;
console.log("\n运行时看这个变量：", typeof price, "← 是 JS 的 number，不是 TS 的类型");

// 想知道 node 实际执行的是什么，让 tsc 把类型擦除的结果输出出来看看：
//
//   npx tsc 01-basics/01-why-typescript.ts --outDir /tmp/out
//   cat /tmp/out/01-why-typescript.js
//
// 你会看到 : number、: string、<T> 这些全都不见了，剩下的就是普通 JS。

// ============================================
// 四、TS 不做的事
// ============================================
// 这两点最容易误会，后面每一章几乎都会碰到：

// 1. TS 不做运行时的数据校验
//
//    假如有一个接口返回 JSON，你写：
//      const res: User = await fetch(...).then(r => r.json());
//    这只是"你告诉 TS 它是 User"，TS 也照你说的信了。
//    如果服务器真的返回了别的东西，运行时照样出错，TS 帮不了你。
//    （需要真正的运行时校验，得用 zod 这类库。）
//
//    这就像 C++ 里的类型转换：你写了 (User*)ptr，编译器就信你。

// 2. TS 不做类型转换
//
//    double("3") 传字符串，JS 会偷偷转成数字；TS 不转，它直接不让你写。
//    TS 里的类型是"描述"，不是"指令"。

// ============================================
// 小结
// ============================================
// - TS 把"运行时才发现的错"提前到"写代码的时候发现"
// - 类型标注语法是 `名字: 类型`，类型写在后面
// - 类型只在编译期存在，运行时被完全擦除，没有性能开销
// - node 只擦类型不检查，tsc 只检查不运行，两个命令配合用

console.log("\n提示：取消文件里任意一处注释，再跑 npm run check，就能看到真实的报错。");
